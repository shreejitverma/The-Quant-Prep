"""Generate the master and per-topic formula sheets from block embeds in the LM notes.

Formulas are never written here by hand; each entry is an embed of ^f-<code>-<lm>-<n> in its LM note.
"""
from __future__ import annotations

import sys

from cfa_common import F_ID, L2, TOPICS, read_frontmatter


def main() -> int:
    sheets = L2 / "40-Formula-Sheets"
    sheets.mkdir(exist_ok=True)
    master = ["---", "type: cfa-formula-sheet", "tags: [cfa/l2, cfa/formulas]", "generated: true", "---", "# Master Formula Sheet", "", "Generated by `17-CFA/scripts/cfa_l2/build_formula_sheet.py`; edit the LM notes, not this file.", "Every entry transcludes a formula block from its module, so a fix there propagates here.", ""]
    total = 0
    for code, slug, vol, name, weight in TOPICS:
        folder = L2 / slug
        topic_lines = ["---", "type: cfa-formula-sheet", f"topic_code: \"{code}\"", "tags: [cfa/l2, cfa/formulas]", "generated: true", "---", f"# {name}: Formula Sheet", ""]
        count = 0
        for note in sorted(folder.glob("LM*.md")):
            fm, body = read_frontmatter(note)
            ids = F_ID.findall(body)
            if not ids:
                continue
            topic_lines.append(f"## LM{fm.get('lm', '?')}: {fm.get('title', note.stem)}")
            topic_lines.append("")
            for full, c, lm, n in ids:
                topic_lines.append(f"![[{note.stem}#^{full}]]")
                topic_lines.append("")
                count += 1
        if count:
            (sheets / f"{slug}-Formulas.md").write_text("\n".join(topic_lines) + "\n")
            master.append(f"## {name} ({count})")
            master.append("")
            master.append(f"![[{slug}-Formulas]]")
            master.append("")
        total += count
    (sheets / "Master-Formula-Sheet.md").write_text("\n".join(master) + "\n")
    print(f"formula sheet: {total} formulas across {len(list(sheets.glob('*-Formulas.md')))} topic sheets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
